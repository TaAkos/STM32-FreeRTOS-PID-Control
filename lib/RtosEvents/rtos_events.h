#ifndef RTOS_EVENTS_H
#define RTOS_EVENTS_H

#define SYSTEM_EVENT_RUN_ALLOWED   (1UL << 0)

#define SYSTEM_EVENT_CONTROL_RESET_DONE (1UL << 1)
#define SYSTEM_EVENT_PLANT_RESET_DONE (1UL << 2)

#define SYSTEM_EVENT_HEARTBEAT_CONTROL    (1UL << 3)
#define SYSTEM_EVENT_HEARTBEAT_PLANT      (1UL << 4)
#define SYSTEM_EVENT_HEARTBEAT_COMM       (1UL << 5)
#define SYSTEM_EVENT_HEARTBEAT_SYSMGR     (1UL << 6)


#define SYSTEM_EVENT_HEARTBEAT_MASK       (SYSTEM_EVENT_HEARTBEAT_CONTROL | SYSTEM_EVENT_HEARTBEAT_PLANT | SYSTEM_EVENT_HEARTBEAT_COMM | SYSTEM_EVENT_HEARTBEAT_SYSMGR)

#endif